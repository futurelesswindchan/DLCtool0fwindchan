/**
 * 术语词典 —— 全部界面术语文案的单一事实来源。
 *
 * 宪法 8.1 节：「同一术语在多处出现必须字字相同。
 * 散写在各 .vue 里，改一处漏三处几乎必然发生，
 * 而同一个词在不同页面解释得不一样，比不解释更伤信任。」
 *
 * 故本文件的每一条解释，由组件经由 UiHelpBadge 引用，
 * 而非在各处手写。
 *
 * 结构：key -> { term, short, long? }
 *
 *   term  术语本身（用于检索与对照）
 *   short 一句话解释（L1，两行以内）
 *   long  扩展说明（L2，「为什么你会遇到它」）
 *
 * 调用方导入：
 *   import { glossary, g } from '@/glossary'
 *   glossary.xxx.short    // 用于 UiHelpBadge 的 content prop
 *   g('xxx')              // 等价于 glossary.xxx.short
 */

