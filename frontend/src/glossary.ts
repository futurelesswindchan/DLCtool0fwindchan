/**
 * 快捷取值：`g('empty')` 等价于 `glossary.empty.short`。
 *
 * 取值失败时返回 key 本身（带引号），而不是抛异常——
 * 界面上出现「引号术语」比白屏好得多，且能当场暴露漏加的词条。
 */
export function g(key: string): string {
  const e = glossary[key]
  return e ? e.short : `「${key}」（缺少词条）`
}
